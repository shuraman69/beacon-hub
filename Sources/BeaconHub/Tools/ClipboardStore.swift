import AppKit
import CryptoKit

struct ClipboardItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    var id = UUID()
    var kind: Kind
    var text: String?
    var imageName: String?
    var files: [String]?
    var date: Date
    var appBundleID: String?
    var appName: String?
    var pinned = false

    func sameContent(as other: ClipboardItem) -> Bool {
        kind == other.kind && text == other.text && imageName == other.imageName && files == other.files
    }

    /// Текст для поиска.
    var searchable: String {
        [text, files?.joined(separator: " "), appName].compactMap { $0 }.joined(separator: " ")
    }
}

/// История буфера обмена (замена CopyClip).
///
/// У macOS нет события «буфер изменился», поэтому changeCount опрашивается раз в 0,5 с. Так делают все подобные утилиты.
/// Пароли не сохраняются: менеджеры паролей помечают их типами org.nspasteboard.ConcealedType и т. п.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []

    private let settings: AppSettings
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var saveWork: DispatchWorkItem?

    let directory: URL
    let imagesDirectory: URL
    private var historyFile: URL { directory.appendingPathComponent("history.json") }

    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]
    static let ignoredApps: Set<String> = [
        "com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal",
    ]
    private static let maxTextLength = 200_000
    private static let maxImageBytes = 25 * 1024 * 1024

    init(settings: AppSettings) {
        self.settings = settings
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        directory = base.appendingPathComponent("BeaconHub/Clipboard", isDirectory: true)
        imagesDirectory = directory.appendingPathComponent("images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true)
        load()
    }

    // MARK: - Мониторинг

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        if let bundleID = app?.bundleIdentifier, Self.ignoredApps.contains(bundleID) { return }

        var item: ClipboardItem?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            item = ClipboardItem(kind: .files, files: urls.map(\.path), date: Date())
        } else if let string = pb.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item = ClipboardItem(kind: .text, text: String(string.prefix(Self.maxTextLength)), date: Date())
        } else if settings.clipboardSaveImages, let name = saveImage(from: pb) {
            item = ClipboardItem(kind: .image, imageName: name, date: Date())
        }

        guard var newItem = item else { return }
        newItem.appBundleID = app?.bundleIdentifier
        newItem.appName = app?.localizedName
        insert(newItem)
    }

    private func saveImage(from pb: NSPasteboard) -> String? {
        guard let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff), raw.count < Self.maxImageBytes else { return nil }
        let png: Data
        if pb.data(forType: .png) != nil {
            png = raw
        } else {
            guard let rep = NSBitmapImageRep(data: raw), let data = rep.representation(using: .png, properties: [:]) else {
                return nil
            }
            png = data
        }
        let hash = SHA256.hash(data: png).prefix(12).map { String(format: "%02x", $0) }.joined()
        let name = "\(hash).png"
        let url = imagesDirectory.appendingPathComponent(name)
        if !FileManager.default.fileExists(atPath: url.path) {
            try? png.write(to: url)
        }
        return name
    }

    private func insert(_ new: ClipboardItem) {
        if let index = items.firstIndex(where: { $0.sameContent(as: new) }) {
            var existing = items.remove(at: index)
            existing.date = new.date
            existing.appBundleID = new.appBundleID
            existing.appName = new.appName
            items.insert(existing, at: 0)
        } else {
            items.insert(new, at: 0)
        }
        trim()
        scheduleSave()
    }

    // MARK: - Действия

    /// Кладёт элемент в системный буфер и поднимает его наверх истории.
    func copyToPasteboard(_ item: ClipboardItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text ?? "", forType: .string)
        case .image:
            if let name = item.imageName, let image = NSImage(contentsOf: imagesDirectory.appendingPathComponent(name)) {
                pb.writeObjects([image])
            }
        case .files:
            pb.writeObjects((item.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        lastChangeCount = pb.changeCount // своё изменение не записываем как новое

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            scheduleSave()
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        scheduleSave()
    }

    func delete(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        cleanupImages()
        scheduleSave()
    }

    func clear(keepPinned: Bool = true) {
        items = keepPinned ? items.filter(\.pinned) : []
        cleanupImages()
        scheduleSave()
    }

    func imageURL(for item: ClipboardItem) -> URL? {
        item.imageName.map { imagesDirectory.appendingPathComponent($0) }
    }

    func trim() {
        let limit = settings.clipboardMaxItems
        var unpinned = 0
        let before = items.count
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            return unpinned <= limit
        }
        if items.count != before { cleanupImages() }
    }

    // MARK: - Хранение

    private func cleanupImages() {
        let used = Set(items.compactMap(\.imageName))
        let files = (try? FileManager.default.contentsOfDirectory(atPath: imagesDirectory.path)) ?? []
        for file in files where !used.contains(file) {
            try? FileManager.default.removeItem(at: imagesDirectory.appendingPathComponent(file))
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyFile) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        items = (try? decoder.decode([ClipboardItem].self, from: data)) ?? []
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let snapshot = items
        let file = historyFile
        let work = DispatchWorkItem {
            let encoder = JSONEncoder()
            encoder.dateEncodingStrategy = .iso8601
            if let data = try? encoder.encode(snapshot) {
                try? data.write(to: file, options: [.atomic])
            }
        }
        saveWork = work
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 0.5, execute: work)
    }
}
